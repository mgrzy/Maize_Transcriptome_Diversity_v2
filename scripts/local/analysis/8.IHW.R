#!/usr/bin/env Rscript

suppressPackageStartupMessages({
  library(data.table)
  library(IHW)
  library(ggplot2)
})

setDTthreads(12)

# -------------------------------------------------------------------------
# Settings
# -------------------------------------------------------------------------

input_dir <- "results/full/osca"

group_definition_file <- paste0(
  "results/summary/ihw_covariate_diagnostics/",
  "ihw_distance_group_definition.rds"
)

output_dir <- "results/summary/ihw_distance"
dir.create(output_dir, recursive = TRUE, showWarnings = FALSE)

# Target FDR
alpha <- 0.01

# Reporting threshold for the incomplete p-value list.
# Change to 0.01 only when enough memory is available.
p_keep <- 1e-3

# -------------------------------------------------------------------------
# Input files
# -------------------------------------------------------------------------

lf <- list.files(
  path = input_dir,
  pattern = "^batch[0-9]+\\.txt\\.gz$",
  full.names = TRUE
)

batch_number <- as.integer(
  sub(
    "^batch([0-9]+)\\.txt\\.gz$",
    "\\1",
    basename(lf)
  )
)

lf <- lf[order(batch_number)]

stopifnot(length(lf) > 0L)

# -------------------------------------------------------------------------
# Load the group definitions generated by the diagnostic script
# -------------------------------------------------------------------------

group_definition <- readRDS(group_definition_file)

dist_breaks <- group_definition$breaks
dist_levels <- group_definition$levels
m_groups <- group_definition$m_groups

# Put m_groups in exactly the same order as factor levels
if (!is.null(names(m_groups))) {
  m_groups <- m_groups[dist_levels]
}

# Keep as numeric because counts may be too large for R integer storage
m_groups <- as.numeric(m_groups)

stopifnot(
  length(m_groups) == length(dist_levels),
  length(dist_breaks) == length(dist_levels) + 1L,
  sum(m_groups) == group_definition$total_tests
)

message(
  "Total number of tests: ",
  format(sum(m_groups), big.mark = ",")
)

# -------------------------------------------------------------------------
# Read only p-values below the reporting threshold
#
# Keep integer file and row identifiers rather than character SNP/gene IDs.
# This substantially reduces memory use.
# -------------------------------------------------------------------------

retained <- vector("list", length(lf))

for (j in seq_along(lf)) {
  
  message(
    "Reading ",
    basename(lf[j]),
    " [",
    j,
    "/",
    length(lf),
    "]"
  )
  
  dt <- fread(
    lf[j],
    select = c("BP", "Probe_bp", "p"),
    showProgress = TRUE
  )
  
  # Preserve the original row number within the batch
  dt[, row_in_file := .I]
  
  dt <- dt[
    is.finite(BP) &
      is.finite(Probe_bp) &
      is.finite(p) &
      p >= 0 &
      p <= p_keep
  ]
  
  if (nrow(dt) == 0L) {
    retained[[j]] <- NULL
    rm(dt)
    gc()
    next
  }
  
  dt[, abs_dist := abs(BP - Probe_bp)]
  
  dt <- dt[
    abs_dist >= dist_breaks[1L] &
      abs_dist <= dist_breaks[length(dist_breaks)]
  ]
  
  dt[, dist_group_index := findInterval(
    abs_dist,
    dist_breaks,
    rightmost.closed = TRUE,
    all.inside = TRUE
  )]
  
  retained[[j]] <- dt[
    ,
    .(
      file_index = j,
      row_in_file,
      p,
      abs_dist,
      dist_group_index
    )
  ]
  
  rm(dt)
  gc()
}

ihw_data <- rbindlist(
  retained,
  use.names = TRUE
)

rm(retained)
gc()

message(
  "Retained p-values: ",
  format(nrow(ihw_data), big.mark = ",")
)

# Avoid exact numerical zeros if OSCA output underflowed
ihw_data[p == 0, p := 1e-300]

# Convert group index to the factor required for incomplete-list IHW
ihw_data[, dist_group := factor(
  dist_levels[dist_group_index],
  levels = dist_levels,
  ordered = TRUE
)]

# Number of retained p-values in each group
retained_group_counts <- ihw_data[
  ,
  .N,
  by = dist_group
][
  CJ(dist_group = factor(
    dist_levels,
    levels = dist_levels,
    ordered = TRUE
  )),
  on = "dist_group"
]

retained_group_counts[is.na(N), N := 0]

retained_group_counts[
  ,
  total_tests := m_groups
]

retained_group_counts[
  ,
  retained_fraction := N / total_tests
]

print(retained_group_counts)

fwrite(
  retained_group_counts,
  file.path(output_dir, "retained_pvalues_by_distance_group.tsv"),
  sep = "\t"
)

# Every group should preferably have many retained p-values
if (any(retained_group_counts$N == 0)) {
  stop(
    "At least one distance group has no retained p-values. ",
    "Increase p_keep or reduce the number of groups."
  )
}

# -------------------------------------------------------------------------
# Run IHW
# -------------------------------------------------------------------------

ihw_fit <- ihw(
  pvalues = ihw_data$p,
  covariates = ihw_data$dist_group,
  alpha = alpha,
  covariate_type = "ordinal",
  m_groups = m_groups,
  adjustment_type = "BH",
  nfolds = 5L,
  seed = 1L,
  quiet = FALSE
)

ihw_fit
rejections(ihw_fit)

ihw_data$adj_p <- adj_pvalues(ihw_fit)

ihw_data <- ihw_data[adj_p<0.01]

fwrite(ihw_data, "results/summary/osca/eqtl_padjusted.csv.gz")
